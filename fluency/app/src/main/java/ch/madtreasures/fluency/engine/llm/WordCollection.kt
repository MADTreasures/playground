package ch.madtreasures.fluency.engine.llm

/**
 * Words with several meanings that come up in everyday conversations, in the six core languages,
 * with hint words and translations into the other five (Swiss German variants where they differ).
 * Filled into the user's list once; everything can be edited or deleted there.
 *
 * Entries without a standard change nothing on their own: only a hint word in the same sentence
 * or the user's choice gives a meaning to the model; otherwise the app just shows which meaning
 * the model took. Where a language uses the same word for all meanings (Spanish "banco" for bench
 * and bank), the entry is skipped for that target language.
 */
object WordCollection {
    /** raise when entries are added: "Sammlung ergänzen" adds the new ones */
    const val VERSION = 1

    val entries: List<AmbiguousWord> by lazy { german + swiss + english + french + italian + spanish + portuguese }

    private fun w(
        language: String,
        word: String,
        vararg meanings: AmbiguousWord.Meaning,
        forms: String = "",
        standard: Boolean = false,
        exact: Boolean = false,
    ) = AmbiguousWord(word, language, meanings.toList(), split(forms, ','), standard, exact)

    /** translations: synonyms separated by "/", the first one is given to the model */
    private fun m(
        label: String,
        hints: String,
        de: String? = null,
        ch: String? = null,
        en: String? = null,
        fr: String? = null,
        it: String? = null,
        es: String? = null,
        pt: String? = null,
    ): AmbiguousWord.Meaning {
        val t = linkedMapOf<String, List<String>>()
        de?.let { t["de"] = split(it, '/') }
        ch?.let { t["de-CH"] = split(it, '/') }
        en?.let { t["en"] = split(it, '/') }
        fr?.let { t["fr"] = split(it, '/') }
        it?.let { t["it"] = split(it, '/') }
        es?.let { t["es"] = split(it, '/') }
        pt?.let { t["pt"] = split(it, '/') }
        return AmbiguousWord.Meaning(label, split(hints, ','), t)
    }

    private fun split(s: String, separator: Char) = s.split(separator).map { it.trim() }.filter { it.isNotEmpty() }

